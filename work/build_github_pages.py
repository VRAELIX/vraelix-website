from __future__ import annotations

from pathlib import Path
import os
import shutil
import subprocess
import sys


WORKSPACE = Path.cwd().resolve()
OUTPUT_NAME = Path(os.environ.get("VRAELIX_GITHUB_PAGES_OUTPUT", "github-pages"))
TARGET = (WORKSPACE / OUTPUT_NAME).resolve() if not OUTPUT_NAME.is_absolute() else OUTPUT_NAME.resolve()
SOURCE_ASSETS = (WORKSPACE / "outputs" / "vraelix-premium-site" / "assets").resolve()
MARKER = ".vraelix-github-pages-generated"

if TARGET == WORKSPACE or WORKSPACE not in TARGET.parents:
    raise SystemExit("Refusing to prepare an output outside the project workspace.")
if TARGET.exists():
    if not (TARGET / MARKER).is_file():
        raise SystemExit("The github-pages directory exists but is not marked as generated; move it aside before rebuilding.")
    shutil.rmtree(TARGET)
if not SOURCE_ASSETS.is_dir():
    raise SystemExit("The existing generated VRAELIX assets are missing; there is nothing to publish.")

TARGET.mkdir(parents=True)
shutil.copytree(
    SOURCE_ASSETS,
    TARGET / "assets",
    dirs_exist_ok=True,
    ignore=shutil.ignore_patterns("site-config.js", "*.map"),
)
(TARGET / MARKER).write_text("generated by work/build_github_pages.py\n", encoding="utf-8")

environment = os.environ.copy()
environment["VRAELIX_BUILD_OUTPUT"] = str(TARGET)
environment["VRAELIX_ZAPIER_WEBHOOK_URL"] = ""
environment["VRAELIX_SUPABASE_URL"] = ""
environment["VRAELIX_SUPABASE_PUBLISHABLE_KEY"] = ""
environment["VRAELIX_TURNSTILE_SITE_KEY"] = ""
environment["VRAELIX_ENQUIRY_BACKEND"] = "zapier"

for script in ("work/build_site.py", "work/prepare_github_pages.py", "work/audit_github_pages.py"):
    subprocess.run([sys.executable, script], cwd=WORKSPACE, env=environment, check=True)
